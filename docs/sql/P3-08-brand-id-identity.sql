-- P3-08 · Let the database generate brands.brand_id
-- Run in the Supabase SQL editor (project owner). Apply this BEFORE deploying the
-- P3-08 code change (which stops computing brand_id as max + 1 in addBrand):
-- with the old column and the new code, adding a brand would fail.

-- 1. Inspect the column. Expect is_identity = 'NO' and no default today.
select column_name, data_type, is_nullable, is_identity, column_default
from information_schema.columns
where table_schema = 'public' and table_name = 'brands' and column_name = 'brand_id';

-- 2. Make it an identity column that continues after the current highest id.
--    (Only run this if step 1 showed is_identity = 'NO' and column_default is null.)
do $$
declare
  next_id bigint;
begin
  select coalesce(max(brand_id), 0) + 1 into next_id from public.brands;
  execute format(
    'alter table public.brands alter column brand_id add generated by default as identity (start with %s)',
    next_id
  );
end $$;

-- 3. Check: should now show is_identity = 'YES'.
select column_name, is_identity, identity_generation
from information_schema.columns
where table_schema = 'public' and table_name = 'brands' and column_name = 'brand_id';
